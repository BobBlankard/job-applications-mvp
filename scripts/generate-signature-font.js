import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(__dirname, '..');
const ttfPath = path.join(root, 'public/fonts/GreatVibes-Regular.ttf');
const outPath = path.join(root, 'src/fonts/great-vibes-signature.js');

if (!fs.existsSync(ttfPath)) {
  console.error('Missing font file:', ttfPath);
  process.exit(1);
}

const base64 = fs.readFileSync(ttfPath).toString('base64');
const content = `// Generated by scripts/generate-signature-font.js — Great Vibes (OFL, Google Fonts)
// Do not edit by hand. Re-run: node scripts/generate-signature-font.js

export const GREAT_VIBES_TTF_VFS = 'GreatVibes-Regular.ttf';

const GREAT_VIBES_BASE64 = '${base64}';

const registeredDocs = new WeakSet();

/** Register Great Vibes script font on a jsPDF instance (signature line only). */
export function registerGreatVibesSignatureFont(doc) {
  if (registeredDocs.has(doc)) return;
  doc.addFileToVFS(GREAT_VIBES_TTF_VFS, atob(GREAT_VIBES_BASE64));
  doc.addFont(GREAT_VIBES_TTF_VFS, 'GreatVibes', 'normal');
  registeredDocs.add(doc);
}
`;

fs.mkdirSync(path.dirname(outPath), { recursive: true });
fs.writeFileSync(outPath, content);
console.log(`Wrote ${outPath} (${(content.length / 1024).toFixed(0)} KB)`);
